create table if not exists admins (
 id bigint generated by default as identity primary key,
 username text unique not null, password_hash text not null,
 role text not null default 'Administrator', created_at text not null
);
create table if not exists students (
 id text primary key, name text not null, roll_no text unique not null,
 department text, year text, email text, phone text,
 face_status text not null default 'Pending', face_file text,
 registered_at text not null, active boolean not null default true
);
create table if not exists devices (
 id text primary key, name text not null, location text, status text not null default 'offline',
 ip text, firmware text, battery integer, last_seen text, last_detection text, created_at text not null
);
create table if not exists attendance (
 id text primary key, student_id text not null references students(id),
 device_id text not null references devices(id), date text not null, time text not null,
 status text not null default 'Present', confidence double precision, created_at text not null,
 unique(student_id,date)
);
create index if not exists attendance_date_idx on attendance(date);
